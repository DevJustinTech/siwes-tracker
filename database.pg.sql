-- ------------------------------------------------------------
-- Students (users)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS students (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matric_no           VARCHAR(40)  NOT NULL UNIQUE,
  full_name           VARCHAR(120) NOT NULL,
  email               VARCHAR(160) NOT NULL UNIQUE,
  password_hash       VARCHAR(255) NOT NULL,
  institution         VARCHAR(160),
  course_of_study     VARCHAR(120),
  placement_org       VARCHAR(160),
  industry_supervisor VARCHAR(160),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Daily entries — a student logs one working day
-- (date, hours, what was done)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS log_entries (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id   INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  entry_date   DATE NOT NULL,
  hours_worked NUMERIC(4,1) NOT NULL DEFAULT 8.0,
  work_done    TEXT NOT NULL,
  challenges   TEXT,
  remarks      TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_student_day UNIQUE (student_id, entry_date)
);

-- ------------------------------------------------------------
-- Sessions — Vercel lambdas are ephemeral, so sessions live here
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sessions (
  id            VARCHAR(128) PRIMARY KEY,
  data          TEXT NOT NULL,
  last_activity BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_last_activity_idx ON sessions (last_activity);
